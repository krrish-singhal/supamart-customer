// Keep Splash.dc.html and the supplied browser runtime as the design source.
/* global __dirname */
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const root = path.resolve(__dirname, '..');
const target = path.join(root, 'src/vendor/splashBundle.js');
// The runtime itself contains HTML strings. Escape parser control tokens so an
// inline script cannot enter HTML's double-escaped script state and swallow the page.
const escapeScript = text => text.replace(/<\/script/gi, '<\\/script').replace(/<!--/g, '\\x3c!--').replace(/<script/gi, '\\x3cscript');

function buildSplash() {
  let html = fs.readFileSync(path.join(root, 'Splash.dc.html'), 'utf8');
  html = html.replace(/<script src="\.\/(vendor\/react\.js|vendor\/react-dom\.js|support\.js)"><\/script>/g, (_tag, file) => {
    const prefix = file === 'support.js' ? 'window.__resources = {};\n' : '';
    return `<script>${prefix}${escapeScript(fs.readFileSync(path.join(root, file), 'utf8'))}</script>`;
  });
  const fontFaces = [[400, 'Regular'], [500, 'Medium'], [600, 'SemiBold'], [700, 'Bold'], [800, 'ExtraBold']].map(([weight, name]) => {
    const data = fs.readFileSync(path.join(root, `assets/fonts/PlusJakartaSans-${name}.ttf`)).toString('base64');
    return `@font-face{font-family:'Plus Jakarta Sans';font-weight:${weight};font-style:normal;font-display:swap;src:url(data:font/ttf;base64,${data}) format('truetype')}`;
  }).join('\n');
  html = html.replace(/<link[^>]+fonts\.googleapis\.com[^>]*>/, `<style>${fontFaces}</style>`);
  const bridge = fs.readFileSync(path.join(root, 'src/utils/splashBridge.js'), 'utf8');
  html = html.replace('</body>', `<script>${escapeScript(bridge)}</script>\n</body>`);
  const hash = crypto.createHash('sha256').update(html).digest('hex');
  return `// Generated by scripts/bundle-splash.cjs from Splash.dc.html, vendor/, support.js and local fonts.\n// Preserve vendor license headers in the embedded scripts. Do not edit this file by hand.\nmodule.exports = ${JSON.stringify({ html, hash })};\n`;
}
function bundleSplash({ check = false } = {}) {
  const generated = buildSplash();
  const previous = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : '';
  if (check && previous !== generated) throw new Error('Splash bundle is stale. Run node scripts/bundle-splash.cjs.');
  if (!check && previous !== generated) fs.writeFileSync(target, generated);
}
if (require.main === module) { bundleSplash({ check: process.argv.includes('--check') }); console.log('Designer splash bundle is up to date.'); }
module.exports = { bundleSplash, buildSplash };
